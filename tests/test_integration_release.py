import unittest


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
import integration_release as release


class SignedReleaseTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temporary = tempfile.TemporaryDirectory(prefix='dux-signature-test-')
        cls.home = Path(cls.temporary.name) / 'gnupg'
        cls.home.mkdir(mode=0o700)
        cls.previous_home = os.environ.get('GNUPGHOME')
        os.environ['GNUPGHOME'] = str(cls.home)
        cls.gpg('--passphrase', '', '--quick-generate-key', 'Disposable integration test', 'ed25519', 'cert', '1d')
        listing = cls.gpg('--with-colons', '--list-keys').decode()
        cls.fingerprint = next(line.split(':')[9] for line in listing.splitlines() if line.startswith('fpr:'))
        cls.gpg('--passphrase', '', '--quick-add-key', cls.fingerprint, 'ed25519', 'sign', '1d')
        cls.public = cls.gpg('--export', cls.fingerprint)
        cls.signer = [
            line.split(':')[9]
            for line in cls.gpg('--with-colons', '--list-keys').decode().splitlines()
            if line.startswith('fpr:')
        ][-1]

    @classmethod
    def gpg(cls, *arguments):
        return subprocess.check_output(
            ['gpg', '--batch', '--yes', '--pinentry-mode', 'loopback', *arguments], stderr=subprocess.DEVNULL
        )

    @classmethod
    def tearDownClass(cls):
        subprocess.run(['gpgconf', '--kill', 'all'], check=True)
        if cls.previous_home is None:
            os.environ.pop('GNUPGHOME')
        else:
            os.environ['GNUPGHOME'] = cls.previous_home
        cls.temporary.cleanup()

    def setUp(self):
        self.directory = tempfile.TemporaryDirectory(prefix='dux-release-test-')
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name)
        for name in ('packages/integration', 'desktop/usr/share', 'keys'):
            (self.root / name).mkdir(parents=True)
        (self.root / 'keys/integration-signing.gpg').write_bytes(self.public)
        (self.root / 'keys/integration-signing.fingerprint').write_text(self.fingerprint + '\n')
        (self.root / 'keys/integration-signing.subkey').write_text(self.signer)
        (self.root / 'keys/integration-history-start.json').write_text(
            json.dumps(
                dict(
                    tag='v0.1.0-1',
                    packages={
                        'arch-niri-dux': '0.1.0-1',
                        'arch-niri-dux-baseline': '0.1.0-1',
                        'dux-example-bin': '2.0.0-1',
                    },
                )
            )
        )
        (self.root / 'packages/packages.target').write_text('base\n')
        (self.root / 'desktop/usr/share/example').write_text('Packaged defaults\n')
        (self.root / 'packages/integration/PKGBUILD').write_text('pkgver=0.1.0\npkgrel=1\n')
        self.app_recipe('2.1.0-1')

    def app_recipe(self, version, description='Fixture app'):
        """Declare a reviewed Dux app recipe for VERSION; DESCRIPTION changes its package contents."""
        source = self.root / 'packages/dux-apps/dux-example-bin'
        source.mkdir(parents=True, exist_ok=True)
        pkgver, pkgrel = version.split('-')
        (source / 'PKGBUILD').write_text(description)
        (source / '.SRCINFO').write_text(f'pkgbase = dux-example-bin\n\tpkgver = {pkgver}\n\tpkgrel = {pkgrel}\n')
        recipe = dict(
            name='dux-example-bin',
            source_date_epoch=1234,
            files={name: release.build.digest(source / name) for name in ('PKGBUILD', '.SRCINFO')},
        )
        (self.root / 'packages/dux-apps-recipes.json').write_text(json.dumps([recipe]))
        return recipe

    def fixture_package(self, destination, name, version, arch, description, builder='Test'):
        # Real makepkg output also names its tools in comments and records the build
        # environment; both differ between rebuilds of the same recipe.
        work = destination / '.fixture'
        work.mkdir()
        (work / '.PKGINFO').write_text(
            f'# Generated by {builder}\npkgname = {name}\npkgver = {version}\n'
            f'pkgdesc = {description}\nbuilddate = 1234\npackager = Test\n'
            f'size = 0\narch = {arch}\n'
        )
        (work / '.MTREE').write_bytes(gzip.compress(f'#mtree\n./.PKGINFO sha256digest={builder}\n'.encode()))
        filename = f'{name}-{version}-{arch}.pkg.tar.zst'
        subprocess.run(
            ['bsdtar', '--zstd', '-cf', str(destination / filename), '-C', str(work), '.PKGINFO', '.MTREE'], check=True
        )
        shutil.rmtree(work)
        return dict(name=name, filename=filename, sha256=release.build.digest(destination / filename))

    def packages(self, destination, builder='Test'):
        destination.mkdir()
        archive = release.build.prepare_source(self.root, destination, 1234)
        shutil.copyfile(self.root / 'packages/integration/PKGBUILD', destination / 'integration.PKGBUILD')
        version = release.build.version(self.root)
        entries = [
            self.fixture_package(destination, name, version, 'any', 'Test fixture')
            for name in sorted(release.build.NAMES)
        ]
        apps = []
        for recipe, source, _ in release.apps.recipes(self.root):
            app_version = release.apps.version(source)
            description = (source / 'PKGBUILD').read_text()
            apps.append(
                self.fixture_package(destination, recipe['name'], app_version, 'x86_64', description, builder)
                | dict(version=app_version, recipe=recipe)
            )
        (destination / 'PKGBUILD').unlink()
        manifest = dict(
            version=version,
            source_date_epoch=1234,
            source_sha256=release.build.digest(archive),
            recipe_sha256=release.build.digest(destination / 'integration.PKGBUILD'),
            packages=entries,
            apps=apps,
        )
        (destination / 'integration.manifest.json').write_text(json.dumps(manifest))
        return destination

    def publish(self, packages, history, output, commit='a' * 40):
        release.publish(self.root, packages, history, output, 'v' + release.build.version(self.root), commit)

    def test_split_signing_entrypoint_uses_disposable_secret_and_cleans_home(self):
        import release_key

        packages = self.packages(self.root / 'built')
        scripts = self.root / 'scripts'
        scripts.mkdir()
        # Replace only network publication; run the real import, validation and signing path.
        (scripts / 'publish-integration').write_text(
            'set -euo pipefail\npython '
            + str(ROOT / 'scripts/integration_release.py')
            + ' publish "$1" "$2" "$3" "$4" --tag v0.1.0-1 --commit '
            + 'a' * 40
            + '\n'
        )
        signing_home = Path('/tmp') / ('dux-signing-' + uuid.uuid4().hex)
        ci = release_key.selected_secret(self.home, self.fingerprint, self.signer)
        subprocess.run(
            [
                'bash',
                str(ROOT / 'scripts/sign-integration'),
                str(self.root),
                str(packages),
                str(self.root / 'history'),
                str(self.root / 'signed'),
            ],
            check=True,
            env=os.environ | {'GNUPGHOME': str(signing_home), 'PACKAGE_SIGNING_KEY': ci.decode()},
        )
        self.assertFalse(signing_home.exists())
        release.verify(self.root, self.root / 'signed/integration.manifest.json', current_signer=True)

    def test_history_boundary_rejects_direct_preincident_packages(self):
        old = self.root / 'old'
        self.publish(self.packages(self.root / 'first'), self.root / 'empty', old)
        (self.root / 'packages/integration/PKGBUILD').write_text('pkgver=0.1.0\npkgrel=2\n')
        self.app_recipe('2.1.0-2')
        boundary = dict(
            tag='v0.1.0-2',
            packages={'arch-niri-dux': '0.1.0-2', 'arch-niri-dux-baseline': '0.1.0-2', 'dux-example-bin': '2.1.0-2'},
        )
        (self.root / 'keys/integration-history-start.json').write_text(json.dumps(boundary))
        built = self.packages(self.root / 'fresh')
        with self.assertRaises(ValueError):
            self.publish(built, old, self.root / 'rejected')
        self.publish(built, self.root / 'empty', self.root / 'replacement')
        release.verify(self.root, self.root / 'replacement/integration.manifest.json', current_signer=True)

    def test_signed_release_roundtrip_tampering_and_identity(self):
        packages = self.packages(self.root / 'packages-built')
        signed = self.root / 'releases/v0.1.0-1'
        self.publish(packages, self.root / 'history', signed)
        release.fetch(self.root, self.root / 'fetched', (self.root / 'releases').as_uri())
        for path in signed.glob('*.pkg.tar.zst'):
            self.assertEqual(path.read_bytes(), (self.root / 'fetched' / path.name).read_bytes())
        with self.assertRaisesRegex(ValueError, 'must be empty'):
            release.fetch(self.root, self.root / 'fetched', (self.root / 'releases').as_uri())
        for name in (
            'integration.manifest.json',
            'arch-niri-dux-0.1.0-1-any.pkg.tar.zst',
            'integration.tar',
            'integration.PKGBUILD',
        ):
            path = signed / name
            original = path.read_bytes()
            path.write_bytes(original + b'tampered')
            with self.subTest(asset=name), self.assertRaises((ValueError, subprocess.CalledProcessError)):
                release.fetch(self.root, self.root / ('fetched-' + name), (self.root / 'releases').as_uri())
            path.write_bytes(original)
        (self.root / 'keys/integration-signing.fingerprint').write_text('B' * 40)
        with self.assertRaisesRegex(ValueError, 'pinned identity'):
            release.verify(self.root, signed / 'integration.manifest.json')

    def test_history_is_retained_but_database_only_selects_latest_and_pages_has_no_links(self):
        old = self.root / 'old'
        self.publish(self.packages(self.root / 'first'), self.root / 'empty', old)
        recipe = self.root / 'packages/integration/PKGBUILD'
        recipe.write_text('pkgver=0.1.0\npkgrel=2\n')
        current = self.root / 'current'
        self.publish(self.packages(self.root / 'second'), old, current)
        self.assertTrue((current / 'arch-niri-dux-0.1.0-1-any.pkg.tar.zst').is_file())
        self.assertFalse(any(path.is_symlink() for path in current.iterdir()))
        with tarfile.open(current / 'arch-niri-dux.db') as database:
            self.assertEqual(
                {name.split('/')[0] for name in database.getnames()},
                {'arch-niri-dux-0.1.0-2', 'arch-niri-dux-baseline-0.1.0-2', 'dux-example-bin-2.1.0-1'},
            )
        for suffix in ('db', 'files'):
            alias = current / f'arch-niri-dux.{suffix}'
            self.assertEqual(alias.read_bytes(), (current / (alias.name + '.tar.gz')).read_bytes())
            release.verify(self.root, alias)
        with self.assertRaisesRegex(ValueError, 'newer'):
            self.publish(self.root / 'second', current, self.root / 'replay')

    def test_published_app_version_keeps_its_bytes_and_cannot_change_or_downgrade(self):
        first = self.root / 'first'
        self.publish(self.packages(self.root / 'v1', builder='makepkg A'), self.root / 'empty', first)
        app = 'dux-example-bin-2.1.0-1-x86_64.pkg.tar.zst'
        recipe = self.root / 'packages/integration/PKGBUILD'
        recipe.write_text('pkgver=0.1.0\npkgrel=2\n')
        # Unchanged recipe, but the rebuild's tool versions and environment differ.
        rebuilt = self.packages(self.root / 'v2', builder='makepkg B')
        self.assertNotEqual((rebuilt / app).read_bytes(), (first / app).read_bytes())
        second = self.root / 'second'
        self.publish(rebuilt, first, second)
        self.assertEqual((second / app).read_bytes(), (first / app).read_bytes())
        release.verify(self.root, second / app)
        manifest = json.loads((second / 'integration.manifest.json').read_text())
        self.assertEqual(manifest['apps'][0]['sha256'], release.build.digest(first / app))
        release.validate_manifest(self.root, second)

        recipe.write_text('pkgver=0.1.0\npkgrel=3\n')
        self.app_recipe('2.1.0-1', description='Changed recipe')
        with self.assertRaisesRegex(ValueError, 'without a new pkgrel'):
            self.publish(self.packages(self.root / 'changed'), second, self.root / 'refused-change')
        self.app_recipe('2.0.0-1')
        with self.assertRaisesRegex(ValueError, 'downgrade'):
            self.publish(self.packages(self.root / 'older'), second, self.root / 'refused-downgrade')

        self.app_recipe('2.1.1-1')
        third = self.root / 'third'
        self.publish(self.packages(self.root / 'v3'), second, third)
        with tarfile.open(third / 'arch-niri-dux.db') as database:
            self.assertIn('dux-example-bin-2.1.1-1', {name.split('/')[0] for name in database.getnames()})
        self.assertFalse((third / app).exists())
        release.verify(self.root, third / 'dux-example-bin-2.1.1-1-x86_64.pkg.tar.zst')

    def test_changed_sources_and_commit_cannot_reuse_a_release(self):
        packages = self.packages(self.root / 'built')
        signed = self.root / 'signed'
        self.publish(packages, self.root / 'history', signed)
